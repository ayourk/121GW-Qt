# Writes stock_syms.ld from ../../names.tsv: every named stock 2.05 function as an absolute Thumb symbol
# (address | 1) and every named global as an absolute address, so C patches can call/use them by name.
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
out = ["/* generated by gen_stock_ld.py from names.tsv: stock 2.05 symbols */"]
seen = set()
for line in open(os.path.join(ROOT, "names.tsv")):
    if not line.strip() or line.startswith("#"): continue
    c = line.rstrip("\n").split("\t")
    if len(c) < 3 or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", c[1]) or c[1] in seen: continue
    seen.add(c[1]); a = int(c[0], 16)
    if "f" in c[2]: out.append(f"PROVIDE(stock_{c[1]} = 0x{a | 1:08x});")
    elif "g" in c[2]: out.append(f"PROVIDE(stock_{c[1]} = 0x{a:08x});")
open(os.path.join(HERE, "stock_syms.ld"), "w").write("\n".join(out) + "\n")
print(f"wrote stock_syms.ld: {len(out) - 1} symbols")
