# How much of stock 2.05 is understood, by code bytes: every function (out/functions.tsv) in a tier from names.tsv
# (library / named-high / named-partial / unnamed), crossed with whether the emulator executed it
# (out/coverage.txt from scripts/coverage_sweep.zsh). Writes docs/understanding.md.
import bisect, collections, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
funcs = []
for line in open(os.path.join(ROOT, "out/functions.tsv")).read().splitlines()[1:]:
    c = line.split("\t")
    funcs.append((int(c[0], 16), c[1], int(c[2])))
funcs.sort()
starts = [f[0] for f in funcs]
conf = {}
for line in open(os.path.join(ROOT, "names.tsv")):
    if line.startswith("#") or not line.strip(): continue
    c = line.rstrip("\n").split("\t")
    if len(c) >= 3 and "g" not in c[2]:
        conf[int(c[0], 16)] = (c[1], c[3] if len(c) > 3 else "")
LIB = re.compile(r"^(__aeabi|__iar|RCC_|GPIO_Init|ADC_|PWR_|FLASH_|DATA_EEPROM_|NVIC_|TIM_|DBGMCU_|RTC_ITConfig|"
                 r"SystemInit|SetSysClock|LCD_(Init|Cmd|WaitForSynchro|MuxSegmentCmd|PulseOnDurationConfig|DeadTimeConfig|"
                 r"BlinkConfig|ContrastConfig|UpdateDisplayRequest|GetFlagStatus)$)")

def tier(entry, name):
    if LIB.match(name): return "library"
    if entry in conf:
        txt = conf[entry][1].lower()
        if "library" in txt: return "library"
        if "high" in txt and not re.search(r"\bmedium\b|\blow\b", txt): return "named-high"
        return "named-partial"
    return "unnamed"

covered = collections.Counter()
cov_path = os.path.join(ROOT, "out/coverage.txt")
blocks = {int(x, 16) for x in open(cov_path).read().split()} if os.path.exists(cov_path) else set()
for b in blocks:
    i = bisect.bisect_right(starts, b) - 1
    if i >= 0: covered[funcs[i][0]] += 1

rows = collections.defaultdict(lambda: [0, 0, 0, 0])      # tier -> [funcs, bytes, executed funcs, executed bytes]
for e, n, sz in funcs:
    t = tier(e, n)
    r = rows[t]; r[0] += 1; r[1] += sz
    if covered[e]: r[2] += 1; r[3] += sz
tot_f = sum(r[0] for r in rows.values()); tot_b = sum(r[1] for r in rows.values())
exe_b = sum(r[3] for r in rows.values())

md = ["# How much of firmware 2.05 is understood", "",
      "Generated by scripts/understanding.py from out/functions.tsv (Ghidra 12.2), names.tsv (confidence in each",
      "comment) and out/coverage.txt (basic blocks the stock image executed in scripts/coverage_sweep.zsh: 463 fresh",
      "boots: every dial position, MODE cycles, every key short and long, SETUP edits, boot keys, sleep/wake, BLE, SD",
      "card save/load/logging, calibration mode).",
      "Bytes = Ghidra function body sizes; data tables, strings and the vector table are not functions and not counted.", "",
      "| Tier | Functions | Code bytes | % of code | Executed in emulation (functions / bytes) |",
      "|---|---|---|---|---|"]
for t in ("named-high", "library", "named-partial", "unnamed"):
    r = rows[t]
    md.append(f"| {t} | {r[0]} | {r[1]:,} | {100 * r[1] / tot_b:.1f}% | {r[2]} / {r[3]:,} ({100 * r[3] / max(r[1], 1):.0f}% of tier) |")
md.append(f"| **total** | {tot_f} | {tot_b:,} | 100% | {sum(r[2] for r in rows.values())} / {exe_b:,} ({100 * exe_b / tot_b:.0f}%) |")
md.append("")
md.append("Tiers: **named-high** = read in the decompile and named with high confidence (many also checked by running);")
md.append("**library** = IAR runtime and ST StdPeriph drivers, identified (their behavior is the vendor's); **named-partial** =")
md.append("named with medium/low confidence or from the video project only; **unnamed** = not read yet.")
md.append("")
big = sorted(((sz, e, n) for e, n, sz in funcs if tier(e, n) == "unnamed"), reverse=True)[:25]
md.append("## Largest unread functions")
md.append("")
md.append("| Entry | Bytes | Executed in emulation |")
md.append("|---|---|---|")
for sz, e, n in big:
    md.append(f"| {e:08x} | {sz} | {'yes' if covered[e] else 'no'} |")
open(os.path.join(ROOT, "docs/understanding.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[7:13]))
