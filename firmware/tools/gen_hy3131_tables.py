"""
Generates firmware/src/hy3131_tables.c: the HY3131 register images
(registers 0x20..0x33, 20 bytes per row) used by hy3131_write_mode_registers().

The tables are emitted as the same contiguous blocks they occupy in the
original image, so that a row index beyond the end of one table reads the
same neighbouring bytes as the original does.

    python -P tools/gen_hy3131_tables.py
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FLASH = os.path.join(ROOT, "dumps", "flash.bin")
OUT = os.path.join(ROOT, "firmware", "src", "hy3131_tables.c")
BASE = 0x08000000

# Contiguous blocks of register images in the v2.05 image.
BLOCKS = [("hy3131_cfg_block_a", 0x080285BC, 0x08028A18),
          ("hy3131_cfg_block_b", 0x08028D1C, 0x08028FE4),
          ("hy3131_cfg_block_c", 0x08029150, 0x08029164)]

# Table starts referenced by the code, and which functions use them.
TABLES = [
    (0x080285BC, "function 9, by range"),
    (0x080286D0, "function 12 when PF8 reads low, by range"),
    (0x08028748, "function 12, by range"),
    (0x080288A0, "function 1 by range; function 2 variant; functions 22-24 by 0x200080C6"),
    (0x080288DC, "function 0 (default)"),
    (0x08028904, "function 2 when 0x200080B7 is set, by range"),
    (0x080289C8, "function 2 (default) by range; functions 13-15 by 0x200080C6"),
    (0x08028A04, "function 0 when 0x20008098 is set (patched)"),
    (0x08028D1C, "functions 13-15 by 0x200080C7; functions 16, 18, 20 by range"),
    (0x08028D58, "functions 22-24 by 0x200080C7"),
    (0x08028D94, "functions 17, 19, 21 (and above 0x10 not listed), by range"),
    (0x08028EE8, "calibration record base address per function (26 x u16, little-endian; entry 25 = AC-peak record)"),
    (0x08028F1C, "function 3 by range; function 5 (row 0)"),
    (0x08028F44, "function 4 (default), by range"),
    (0x08028F6C, "function 4 when 0x200080B7 is set, by range"),
    (0x08028F94, "function 11, by range"),
    (0x08028FBC, "functions 6, 7, 8"),
    (0x08029150, "function 10"),
]


def main():
    flash = open(FLASH, "rb").read()
    lines = [
        "/*",
        " * HY3131 register images (registers 0x20..0x33, 20 bytes per row).",
        " * Generated by tools/gen_hy3131_tables.py from the v2.05 image - do not edit.",
        " *",
        " * Kept as the original's contiguous blocks so out-of-range rows read the",
        " * same neighbouring bytes as the original.",
        " */",
        '#include "hy3131_tables.h"',
        "",
    ]
    for name, start, end in BLOCKS:
        data = flash[start - BASE:end - BASE]
        lines.append("/* orig: 0x%08X..0x%08X */" % (start, end - 1))
        lines.append("const uint8_t %s[%d] = {" % (name, len(data)))
        # Rows restart at every table start so each table reads as whole rows.
        cuts = sorted({start, end} | {t for t, _ in TABLES if start <= t < end})
        for seg_start, seg_end in zip(cuts, cuts[1:]):
            desc = next((d for t, d in TABLES if t == seg_start), None)
            if desc:
                lines.append("    /* 0x%08X: %s */" % (seg_start, desc))
            for a in range(seg_start, seg_end, 20):
                row = flash[a - BASE:min(a + 20, seg_end) - BASE]
                lines.append("    " + ", ".join("0x%02X" % b for b in row) + ",")
        lines.append("};")
        lines.append("")
    open(OUT, "w", newline="\n").write("\n".join(lines))

    hdr = os.path.join(ROOT, "firmware", "include", "hy3131_tables.h")
    h = ["/*",
         " * HY3131 register image tables (see hy3131_tables.c).",
         " * Generated by tools/gen_hy3131_tables.py - do not edit.",
         " */",
         "#ifndef HY3131_TABLES_H", "#define HY3131_TABLES_H", "",
         "#include <stdint.h>", "",
         "#define HY3131_CFG_ROW 20u", ""]
    for name, start, end in BLOCKS:
        h.append("extern const uint8_t %s[%d];" % (name, end - start))
    h.append("")
    for t, desc in TABLES:
        for name, start, end in BLOCKS:
            if start <= t < end:
                h.append("#define HY3131_CFG_%08X (%s + 0x%03X)   /* %s */" % (t, name, t - start, desc))
    h += ["", "#endif /* HY3131_TABLES_H */", ""]
    open(hdr, "w", newline="\n").write("\n".join(h))
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(hdr, ROOT))


if __name__ == "__main__":
    main()
