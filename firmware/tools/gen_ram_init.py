"""
Generates firmware/src/ram_init.c: the initial contents of RAM
0x20000000..0x2000023D, which the original start-up code decompresses from
its IAR LZ77 initialiser (dumps/app_data_init.bin, see tools/iar_lz77.py).

It holds the initialised variables (defaults such as the log interval and
LCD contrast, the ranges per function, the log texts, the RCC prescaler
tables...). Each named variable in the range is listed in a comment.

    python -P tools/gen_ram_init.py
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BASE = 0x20000000


def main():
    image = open(os.path.join(ROOT, "dumps", "app_data_init.bin"), "rb").read()
    labels = {}
    for line in open(os.path.join(ROOT, "ghidra", "app_names.tsv")):
        if line.startswith("#") or not line.strip():
            continue
        f = line.rstrip("\n").split("\t")
        addr = int(f[0], 16)
        if BASE <= addr < BASE + len(image) and f[1] == "label":
            labels[addr] = f[2]
    out = [
        "/*",
        " * Initial contents of RAM 0x20000000..0x%08X, copied there by the start-up" % (BASE + len(image) - 1),
        " * code (the original decompresses the same bytes from an IAR LZ77 initialiser).",
        " * Generated by tools/gen_ram_init.py from the v2.05 image - do not edit.",
        " *",
        " * Named variables in this range:",
    ]
    for addr in sorted(labels):
        out.append(" *   0x%08X  %s" % (addr, labels[addr]))
    out += [" */", "#include <stdint.h>", "",
            "const uint8_t g_ram_init_image[%d] = {" % len(image)]
    for i in range(0, len(image), 16):
        chunk = image[i:i + 16]
        out.append("    " + " ".join("0x%02X," % b for b in chunk) + "  /* 0x%08X */" % (BASE + i))
    out.append("};")
    open(os.path.join(ROOT, "firmware", "src", "ram_init.c"), "w").write("\n".join(out) + "\n")
    print("wrote firmware/src/ram_init.c (%d bytes, %d named variables)" % (len(image), len(labels)))


if __name__ == "__main__":
    main()
