"""
Generates an assembly file that binds every symbol the rebuilt modules
reference but do not define to its address in the original v2.05 image.

Names come from ghidra/app_names.tsv; FUN_xxxxxxxx and DAT_xxxxxxxx resolve
to the address in their name. Functions are emitted with .thumb_set so calls
stay in Thumb state.

    python -P tools/hybrid_syms.py <library.a> <output.s> [--ram-only]

With --ram-only (the standalone application image) only RAM variables may
be bound; any function still taken from the original image is an error.
"""
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def names():
    out = {}
    for line in open(os.path.join(ROOT, "ghidra", "app_names.tsv")):
        if line.startswith("#") or not line.strip():
            continue
        f = line.rstrip("\n").split("\t")
        out[f[2]] = (int(f[0], 16), f[1])
    return out


def main():
    lib, dest = sys.argv[1], sys.argv[2]
    ram_only = "--ram-only" in sys.argv[3:]
    from_original = []
    nm = subprocess.run(["arm-none-eabi-nm", lib], capture_output=True, text=True, check=True).stdout
    defined, undefined = set(), set()
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3:
            defined.add(parts[2])
    table = names()
    lines = ["/* generated by tools/hybrid_syms.py - do not edit */", "    .syntax unified",
             "    .thumb"]
    missing = []
    for sym in sorted(undefined - defined):
        if sym in table:
            addr, kind = table[sym]
        elif sym.startswith("FUN_"):
            addr, kind = int(sym[4:], 16), "func"
        elif sym.startswith("DAT_"):
            addr, kind = int(sym[4:], 16), "label"
        elif sym.startswith("__aeabi_") or sym.startswith("__gnu_"):
            continue   # supplied by libgcc
        else:
            missing.append(sym)
            continue
        if ram_only and not (0x20000000 <= addr < 0x20010000):
            from_original.append(sym)
            continue
        lines.append("    .global %s" % sym)
        if kind == "func":
            lines.append("    .type %s, %%function" % sym)
            lines.append("    .thumb_set %s, 0x%08X" % (sym, addr | 1))
        else:
            lines.append("    .set %s, 0x%08X" % (sym, addr))
    if from_original:
        sys.exit("standalone image still needs the original image for: " + ", ".join(from_original))
    if missing:
        sys.exit("unresolved symbols (add them to ghidra/app_names.tsv): " + ", ".join(missing))
    open(dest, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
